"""Render the original, clearly illustrative Nexus media graphic with stdlib only."""
import struct, zlib
from pathlib import Path
W, H = 1920, 1080
bg = (20, 37, 32)
pixels = bytearray(bg * (W * H))
def rect(x, y, w, h, c):
    x0, y0, x1, y1 = max(0,x), max(0,y), min(W,x+w), min(H,y+h)
    row = bytes(c) * max(0,x1-x0)
    for yy in range(y0,y1):
        start=(yy*W+x0)*3; pixels[start:start+len(row)] = row
def text(s,x,y,scale,c):
    for ch in s.upper():
        glyph=FONT.get(ch,FONT[' '])
        for gy,row in enumerate(glyph):
            for gx,b in enumerate(row):
                if b=='1': rect(x+gx*scale,y+gy*scale,scale,scale,c)
        x += 6*scale
